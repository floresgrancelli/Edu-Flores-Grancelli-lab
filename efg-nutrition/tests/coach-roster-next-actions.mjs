import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {currentCoachIntakeDraft} from '../pilot/coach-intake-queue.js';
const source=readFileSync(new URL('../pilot/pilot.js',import.meta.url),'utf8');
const state={coachIntakeVerified:true,coachIntakeDraftVerified:true,coachIntakeForms:{},coachIntakeGoals:{},coachIntakeAccess:{},coachIntakeDraftStatuses:{},org:{id:'org'},session:{user:{id:'coach'}}};
const consent={},context=vm.createContext({state,coachRosterConsent:consent,currentCoachIntakeDraft});
vm.runInContext(source.slice(source.indexOf('function coachRosterNext('),source.indexOf('function coachRosterCard(')),context);
const person=id=>({user_id:id,active:true});
const a=person('a');consent.a=true;
assert.equal(context.coachRosterNext(a).stage,'plan','Optional intake is not required');
state.coachIntakeForms.a={student_id:'a',organization_id:'org',revision:2,shared_at:'2026-11-11'};
assert.equal(context.coachRosterNext(a).stage,'intake');
state.coachIntakeAccess.a={status:'published'};
assert.equal(context.coachRosterNext(a).stage,'follow');
state.coachIntakeDraftStatuses.a={student_id:'a',organization_id:'org',coach_id:'coach',status:'draft',draft_revision:1,source_intake_revision:2};
assert.equal(context.coachRosterNext(a).stage,'draft','Current private draft takes priority over an older published plan');
assert.equal(context.coachRosterNext(a).section,'coachStudentGoals');
state.coachIntakeDraftStatuses.a.source_intake_revision=1;
assert.equal(context.coachRosterNext(a).stage,'follow','Stale draft cannot be offered for continuation');
state.coachIntakeDraftStatuses.a.source_intake_revision=2;
state.coachIntakeDraftStatuses.a.coach_id='another';
assert.equal(context.coachRosterNext(a).stage,'follow','Another coach draft cannot be advertised');
state.coachIntakeDraftStatuses.a.coach_id='coach';
consent.a=false;assert.equal(context.coachRosterNext(a).stage,'consent');
assert.equal(context.coachRosterNext({...a,active:false}).stage,'inactive');
consent.a=true;state.coachIntakeVerified=false;
assert.equal(context.coachRosterNext(a).stage,'unknown');
assert.equal(context.coachRosterMatches('unknown','pending'),false);
assert.equal(context.coachRosterMatches('draft','pending'),true);
assert.equal(context.coachRosterMatches('draft','plan'),true);
assert.equal(context.coachRosterMatches('inactive','pending'),false);
state.coachIntakeVerified=true;
const roster=[person('follow'),person('plan'),a,person('intake'),person('plan2'),{...person('inactive'),active:false}];
for(const p of roster)consent[p.user_id]=true;
state.coachIntakeAccess.follow={status:'published'};
state.coachIntakeForms.intake={shared_at:'2026-11-11'};
const before=JSON.stringify(roster);
assert.deepEqual(Array.from(context.coachRosterOrdered(roster),p=>p.user_id),['intake','a','plan','plan2','follow','inactive']);
assert.equal(JSON.stringify(roster),before,'Priority order must not mutate the source roster');
assert.match(context.coachRosterFilters(roster),/Pendientes · 4/);
assert.match(context.coachRosterFilters(roster),/Planes pendientes · 3/);
console.log('PASS roster next actions: current draft priority, consent boundaries, stale drafts, stable pending order and filter counts');
