// Fase 3 - QA contractual, sin cuentas, red ni Supabase.
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {pastelDaySummary,FILLED_FATS_ICON} from "../pilot/pastel-day.js";
const read=name=>readFileSync("efg-nutrition/pilot/"+name,"utf8");
const html=read("index.html"),app=read("pilot.js"),css=read("pastel-system.css"),luxury=read("luxury-theme.css");
const mealSlots=[["desayuno"],["media_manana"],["almuerzo"],["media_tarde"],["merienda"],["cena"]];
const totals={k:1250,p:85,c:120,f:40,fi:22};
const goals={k:2000,p:155,c:230,f:65,fi:30};
const diary={meals:{desayuno:[{k:320}],almuerzo:[{k:550}],merienda:[{k:380}],media_manana:[],media_tarde:[],cena:[]},skipped:{}};
const out=pastelDaySummary(totals,goals,diary,mealSlots);
assert.match(out,/Resumen de hoy/);
assert.match(out,/1\.250/);
assert.match(out,/2\.000/);
assert.match(out,/750<\/strong><small>kcal restantes/);
assert.match(out,/3<\/strong><small>comidas registradas/);
assert.match(out,/22 g<\/strong><small>fibra registrada/);
assert.doesNotMatch(out,/data-openquickadd|efg-pastel-register|Registrar alimento/,"No redundant button within calorie summary");
assert.match(out,/--ring-c:225\.00deg/,"1250/2000 = 62.5% -> 225 degrees");
assert.match(out,/--macro-progress:54\.84%/,"Protein 85/155");
assert.match(out,/--macro-progress:52\.17%/,"Carbs 120/230");
assert.match(out,/--macro-progress:61\.54%/,"Fat 40/65");
assert.match(out,/Los colores son decorativos|colores son decorativos/);
assert.ok(!out.includes("6.200")&&!out.includes("1,5 L"),"Never invent hydration or activity");
const over=pastelDaySummary({...totals,k:2300},{...goals,k:2000},diary,mealSlots);
assert.match(over,/\+300<\/strong><small>kcal sobre meta/,"Do not hide excess energy");
assert.match(over,/--ring-c:360\.00deg/);
const noGoal=pastelDaySummary(totals,null,diary,mealSlots);
assert.match(noGoal,/Objetivo pendiente del coach/);
assert.match(noGoal,/sin meta de kcal/);
assert.ok(!noGoal.includes("de 0 g"),"Never invent a zero target");
const skipped=pastelDaySummary(totals,goals,{...diary,skipped:{almuerzo:true}},mealSlots);
assert.match(skipped,/2<\/strong><small>comidas registradas/);
assert.ok(FILLED_FATS_ICON.includes("<svg")&&FILLED_FATS_ICON.includes("Palta y aceituna"));
assert.ok(!FILLED_FATS_ICON.includes("💧"),"Never use water droplet for fats");
assert.ok(css.includes("--pastel-lilac")&&css.includes("--pastel-coral")&&css.includes("--pastel-amber")&&css.includes("--pastel-blue"));
assert.ok(css.includes(".efg-role-coach")||css.includes(".efg-coach-banner"),"Coach included");
assert.ok(css.includes(".efg-admin-banner"),"Admin included");
assert.ok(css.includes(".efg-pastel-ring"),"Calorie ring implemented");
assert.ok(app.includes('return rootText("MI DÍA"'),"Main daily heading is uppercase");
assert.ok(app.includes('["home","⌂","MI DÍA"]'),"Student navigation label uppercase");
assert.ok(app.includes('["home","🍽️","MI DÍA","mint"]'),"Admin access uses same label MI DÍA");
assert.match(app,/\["adminManage","⚙️","Organizaciones","lilac"\]/,"Admin management entry uses a single legible word");
assert.match(app,/\["messages","💬","Mensajería interna","mint"\]/,"Admin messaging has a real-product label");
assert.doesNotMatch(app,/Gestionar organizaciones|Mensajes de prueba/,"Retire misleading or broken labels in admin shortcuts");

assert.doesNotMatch(app,/5 cupos gratuitos de prueba/,"Test seat limit must not be hard-coded");
assert.match(app,/seats=Number\(org\?\.seat_limit\)\|\|0/,"Seat limit comes from actual organization config");
assert.match(app,/available=Math\.max\(0,seats-used\)/,"Available seats subtract active members and pending invitations");
assert.match(app,/data-testseats="1"/,"Admin can update test capacity using existing admin-only RPC");
assert.match(app,/data-act="inviteStudent".*used>=seats/,"Invite is disabled only when the real limit is reached");
assert.match(luxury,/\.efg-seats-panel/,"Premium seat capacity panel retains Luxury aesthetic");

assert.ok(css.includes("text-transform:uppercase"),"CSS applies uppercase titles and buttons");
assert.ok(css.includes(".efg-coach-stat-grid>div"),"Coach and admin stat panels have pastel surfaces");
assert.ok(css.includes("--pastel-bg:#D9C5E9"),"Deepened lavender canvas");
assert.ok(!app.includes('class="brand-mark"'),"No decorative logo box in desktop header");
assert.ok(!app.includes('class="efg-mobile-monogram"'),"No decorative logo box in mobile header");
assert.ok(app.includes('class="efg-mobile-brand-text"'),"Keep the full EFG Nutrition name");
assert.ok(css.includes("--pastel-surface:#FAECF2"),"Dusty rose cards");
assert.ok(html.includes('name="theme-color" content="#DCD8D2"'),"iPhone theme-color matches luxury stone canvas");
assert.ok(html.lastIndexOf("pastel-system.css")>html.lastIndexOf("premium-system.css"),"Pastel base comes after premium");
assert.ok(html.lastIndexOf("luxury-theme.css")>html.lastIndexOf("weekly-consistency.css"),"Luxury preview must load last");
assert.ok(luxury.includes("--lux-night:#142439")&&luxury.includes("--lux-gold:#b08b4e"),"Premium night blue and gold palette");
assert.ok(luxury.includes("repeating-linear-gradient")&&luxury.includes("inset 0"),"Material textures and raised cards exist");
assert.ok(luxury.includes("Do not override background/conic-gradient"),"Vivid macro charts are explicitly preserved");
assert.ok(!luxury.includes("filter:grayscale"),"Never desaturate charts");
assert.match(app,/pastelDaySummary\(tot,goal,d,mealSlots\)/);
assert.ok(!app.includes("el.dataset.openquickadd"),"Obsolete quick-add handler must be removed");
assert.doesNotMatch(app,/id="studentQuickAdd"/,"Duplicate colored meal selector removed");
assert.match(app,/id="studentMeals"/,"Meal diary retained");
assert.match(app,/data-setmeal=/,"Direct add control remains in each meal");
assert.match(app,/\+ Añadir alimento/,"Meal card must preserve add action");
assert.match(app,/\.from\("efg_consents"\)/,"Consent workflow retained");
assert.match(app,/id="studentMeals"/,"Diary retained");
assert.doesNotMatch(app,/if\(el\.dataset\.openquickadd\)/,"No redundant quick-add redirect");
assert.match(app,/studentGuidedSection\(\)/,"Coach guide must not insert food into diary");
const balance={open:(css.match(/{/g)||[]).length,close:(css.match(/}/g)||[]).length};
assert.equal(balance.open,balance.close,"CSS bracket balance");
console.log("PASS: pastel system macro math, no-goal, over-goal, six meal slots, skipped meals, semantic filled avocado+olive, global roles and existing privacy.");
