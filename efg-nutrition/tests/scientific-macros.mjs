import assert from "node:assert/strict";
import "./diet-pattern-workbench.mjs"; // New nonclinical Coach / Personal contract tests.
import {readFileSync} from "node:fs";
const src=readFileSync("efg-nutrition/pilot/macro-engine.js","utf8");
const {estimateMacros,ACTIVITY_LEVELS,RECOMP_STRATEGIES}=await import("data:text/javascript;base64,"+Buffer.from(src).toString("base64"));
assert.deepEqual(ACTIVITY_LEVELS.map(x=>x.value),[1.2,1.35,1.5]);
assert.deepEqual(RECOMP_STRATEGIES.map(x=>x.id),["maintenance","deficit05","deficit10"]);
const inputs={age:41,height:174,weight:77.55,activity:1.5,sex:"male",goal:"recomp",model:"mifflin",fatPerKg:.9};
const a=estimateMacros({...inputs,recompMode:"deficit10"});
assert.equal(a.rmr,1663);assert.equal(a.maintenance,2495);assert.equal(a.kcal,2250);
assert.equal(a.protein,155);assert.equal(a.fat,70);assert.equal(a.carbs,250);assert.equal(a.fiber,32);
assert.ok(Math.abs(a.protein*4+a.fat*9+a.carbs*4-a.kcal)<=2);
const b=estimateMacros({...inputs,recompMode:"deficit05"}),c=estimateMacros({...inputs,recompMode:"maintenance"});
assert.ok(c.kcal>b.kcal&&b.kcal>a.kcal);assert.equal(c.kcal,2500);
assert.equal(a.proteinFactor,2);assert.equal(a.fatFactor,.9);
const female=estimateMacros({...inputs,sex:"female",recompMode:"deficit10"});
assert.equal(female.rmr,1497);assert.ok(female.kcal<a.kcal);
assert.equal(female.protein,a.protein);assert.equal(female.fat,a.fat);
assert.ok(female.carbs<a.carbs);
assert.throws(()=>estimateMacros({...inputs,activity:1.7}),/actividad/);
assert.throws(()=>estimateMacros({...inputs,activity:1.55}),/actividad/);
assert.throws(()=>estimateMacros({...inputs,sex:"other"}),/sexo/);
assert.equal(estimateMacros({...inputs,goal:"muscle_gain"}).proteinFactor,1.8);
const override=estimateMacros({...inputs,proteinPerKg:1.8,fatPerKg:.8,recompMode:"maintenance"});
assert.equal(override.protein,140);assert.equal(override.fat,62);
const femaleVar=estimateMacros({age:35,height:162,weight:63,activity:1.35,sex:"female",goal:"recomp",recompMode:"deficit05"});
assert.ok(femaleVar.kcal>1400&&femaleVar.protein>0&&femaleVar.fat>0&&femaleVar.carbs>0);
const app=readFileSync("efg-nutrition/pilot/pilot.js","utf8");
assert.ok(app.includes("estimateMacros({age,height,weight,activity,sex,goal,model,proteinPerKg,fatPerKg,recompMode})"));
assert.ok(app.includes("ACTIVITY_LEVELS")&&app.includes("RECOMP_STRATEGIES"));
assert.ok(app.includes('id="targetRecompMode"')&&app.includes('id="previewRecompMode"'));
assert.ok(!app.includes('[1.7,"Alta"]')&&!app.includes('<option value="1.7">Alta</option>'));
assert.ok(!app.includes("activity>=1.2&&activity<=1.75"));
assert.ok(app.includes('<option value="">Seleccioná hombre o mujer</option>'),"Explicit sex is required before calculating coach proposals");
assert.ok(app.includes("invalidateCoachDraft(e)"),"Changing inputs must invalidate stale proposal approval");
console.log("PASS: sexo hombre/mujer, recomp 0/-5/-10%, top 1.50, P 2g/kg, G 0.9g/kg, carbos y validaciones.");
