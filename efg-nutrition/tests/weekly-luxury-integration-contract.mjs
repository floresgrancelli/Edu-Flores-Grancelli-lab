assert.match(ui,/await messages\.replyToWeeklyReport\(state\.session\.user\.id,week\)/);
assert.match(ui,/myWeeklyReports\.some\(r=>r\.week_ending===week/);
assert.match(chat,/async function replyToWeeklyReport\(student,weekEnding\)/);
assert.match(chat,/c\.role!=="student"/);
assert.match(chat,/await openStudent\(student\)/);
